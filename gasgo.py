import csv

# Constants
CYLINDER_PRICE = 900.0
SUBSIDY_AMOUNT = 200.0

# Global State (Lists of Dictionaries)
consumers = []
bookings = []
agency_stock = 25
current_day = 12

def load_sample_data():
    """Preloads realistic data so the 2-minute live demo is fast and seamless."""
    global consumers, bookings, agency_stock, current_day
    consumers = [
        {"id": 101, "name": "Arjun Mehta", "area": "RT Nagar", "type": 1, "subsidy": True, "last_delivery": 1},
        {"id": 102, "name": "Priya Sharma", "area": "Indiranagar", "type": 2, "subsidy": False, "last_delivery": 10},
        {"id": 103, "name": "Ramesh Rao", "area": "RT Nagar", "type": 1, "subsidy": True, "last_delivery": -1}
    ]
    bookings = [
        {"booking_id": 5001, "consumer_id": 103, "booking_day": 1, "delivery_day": -1, "status": "Pending", "payable": 700.0}
    ]
    agency_stock = 24  # 1 reserved from initial 25
    current_day = 12

def get_int_input(prompt):
    """Safely reads an integer and handles wrong input without crashing."""
    while True:
        user_in = input(prompt).strip()
        try:
            return int(user_in)
        except ValueError:
            print("  [Error] Invalid input! Please enter a valid whole number.")

def find_consumer(cid):
    """Returns the consumer dictionary matching the ID, or None."""
    for c in consumers:
        if c["id"] == cid:
            return c
    return None

# CORE FEATURE 1: Register consumers with connection type (single or double cylinder)
def register_consumer():
    new_id = 101 + len(consumers)
    print(f"\n--- Register New Consumer (Assigned ID: {new_id}) ---")

    name = input("Enter Consumer Name: ").strip()
    while not name:
        print("  [Error] Name cannot be empty.")
        name = input("Enter Consumer Name: ").strip()

    area = input("Enter Delivery Area (e.g., RT Nagar, Hebbal): ").strip()
    while not area:
        print("  [Error] Area cannot be empty.")
        area = input("Enter Delivery Area: ").strip()

    while True:
        conn_type = get_int_input("Connection Type (1 = Single Cylinder, 2 = Double Cylinder): ")
        if conn_type in (1, 2):
            break
        print("  [Error] Please enter 1 or 2 only.")

    while True:
        sub_choice = get_int_input("Eligible for Subsidy? (1 = Yes, 0 = No): ")
        if sub_choice in (0, 1):
            break
        print("  [Error] Please enter 1 or 0 only.")

    consumers.append({
        "id": new_id,
        "name": name,
        "area": area,
        "type": conn_type,
        "subsidy": (sub_choice == 1),
        "last_delivery": -1
    })
    print(f"[Success] Consumer '{name}' registered with ID {new_id}.")

# CORE FEATURE 2: Book a refill only if minimum gap since last delivery has passed
def book_refill():
    global agency_stock
    if agency_stock <= 0:
        print("\n[Error] Out of stock! Please restock filled cylinders first.")
        return

    cid = get_int_input("\nEnter Consumer ID: ")
    consumer = find_consumer(cid)
    if not consumer:
        print(f"[Error] Consumer ID {cid} not found.")
        return

    # Prevent duplicate active pending bookings for the same consumer
    for b in bookings:
        if b["consumer_id"] == cid and b["status"] == "Pending":
            print(f"[Rejected] Consumer already has a Pending booking (Booking ID: {b['booking_id']}).")
            return

    # Minimum gap rule: 15 days for Single Cylinder, 7 days for Double Cylinder
    min_gap = 15 if consumer["type"] == 1 else 7

    if consumer["last_delivery"] != -1:
        days_elapsed = current_day - consumer["last_delivery"]
        if days_elapsed < min_gap:
            print(f"[Rejected] Minimum gap of {min_gap} days not met!")
            print(f"           Last delivery: Day {consumer['last_delivery']} | Current Day: {current_day} | Elapsed: {days_elapsed} days.")
            return

    # STRETCH FEATURE: Apply subsidy flags and show subsidy amount
    payable = CYLINDER_PRICE - SUBSIDY_AMOUNT if consumer["subsidy"] else CYLINDER_PRICE
    new_booking_id = 5001 + len(bookings)

    bookings.append({
        "booking_id": new_booking_id,
        "consumer_id": cid,
        "booking_day": current_day,
        "delivery_day": -1,
        "status": "Pending",
        "payable": payable
    })
    agency_stock -= 1

    print("\n[Success] Refill Booked!")
    print(f"  Booking ID      : {new_booking_id}")
    print(f"  Consumer        : {consumer['name']} ({consumer['area']})")
    print(f"  Booking Day     : Day {current_day}")
    print(f"  Base Price      : Rs. {CYLINDER_PRICE:.2f}")
    if consumer["subsidy"]:
        print(f"  Subsidy Applied : -Rs. {SUBSIDY_AMOUNT:.2f}")
    print(f"  Net Payable     : Rs. {payable:.2f}")
    print(f"  Remaining Stock : {agency_stock} cylinders")

# CORE FEATURE 3: Track delivery status
def manage_deliveries():
    print(f"\n--- All Refill Bookings (Current Day: {current_day}) ---")
    if not bookings:
        print("No bookings recorded yet.")
        return

    print(f"{'Book_ID':<10} {'Cons_ID':<10} {'Name':<18} {'Book_Day':<10} {'Status':<12} {'Payable':<10}")
    print("-" * 74)
    for b in bookings:
        c = find_consumer(b["consumer_id"])
        print(f"{b['booking_id']:<10} {b['consumer_id']:<10} {c['name']:<18} Day {b['booking_day']:<6} {b['status']:<12} Rs.{b['payable']:.2f}")

    choice = get_int_input("\nMark a Pending booking as Delivered? (1 = Yes, 0 = No): ")
    if choice == 1:
        bid = get_int_input("Enter Booking ID to mark Delivered: ")
        for b in bookings:
            if b["booking_id"] == bid:
                if b["status"] != "Pending":
                    print(f"[Error] Booking {bid} is already marked as {b['status']}.")
                    return
                b["status"] = "Delivered"
                b["delivery_day"] = current_day
                c = find_consumer(b["consumer_id"])
                c["last_delivery"] = current_day
                print(f"[Success] Booking {bid} marked as DELIVERED on Day {current_day}.")
                return
        print(f"[Error] Booking ID {bid} not found.")

# CORE FEATURE 4: Track agency stock of filled cylinders
def manage_stock():
    global agency_stock
    print("\n--- Agency Cylinder Inventory ---")
    print(f"Current Filled Cylinders in Stock: {agency_stock}")
    added = get_int_input("Enter new filled cylinders received from plant (0 to skip): ")
    if added < 0:
        print("[Error] Cannot add a negative number of cylinders.")
        return
    agency_stock += added
    print(f"[Success] Updated Stock: {agency_stock} filled cylinders.")

# CORE FEATURE 5: List pending bookings older than 3 days
def list_delayed_bookings():
    print(f"\n--- Pending Bookings Older Than 3 Days (Current Day: {current_day}) ---")
    found = False
    for b in bookings:
        if b["status"] == "Pending":
            age = current_day - b["booking_day"]
            if age > 3:
                c = find_consumer(b["consumer_id"])
                print(f"Booking ID: {b['booking_id']} | Consumer: {c['name']} (ID: {c['id']}) | Area: {c['area']} | Booked: Day {b['booking_day']} | Pending: {age} days")
                found = True
    if not found:
        print("No pending bookings older than 3 days.")

# STRETCH FEATURE: Plan deliveries by area
def plan_deliveries_by_area():
    target_area = input("\nEnter Area Name to filter pending deliveries: ").strip()
    print(f"\n--- Delivery Route Plan for Area: {target_area} ---")
    count = 0
    for b in bookings:
        if b["status"] == "Pending":
            c = find_consumer(b["consumer_id"])
            if c["area"].lower() == target_area.lower():
                cyl_str = "Single" if c["type"] == 1 else "Double"
                print(f"  -> Booking ID: {b['booking_id']} | Consumer: {c['name']} | Type: {cyl_str} | Collect: Rs.{b['payable']:.2f}")
                count += 1
    if count == 0:
        print(f"No pending deliveries found for area '{target_area}'.")
    else:
        print(f"Total cylinders to load on truck for {target_area}: {count}")

# STRETCH FEATURE (General Rule): Save records to CSV file
def export_to_csv():
    with open("gasgo_bookings.csv", "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["Booking_ID", "Consumer_ID", "Consumer_Name", "Area", "Booking_Day", "Delivery_Day", "Status", "Payable_Rs"])
        for b in bookings:
            c = find_consumer(b["consumer_id"])
            writer.writerow([b["booking_id"], b["consumer_id"], c["name"], c["area"], b["booking_day"], b["delivery_day"], b["status"], b["payable"]])
    print("\n[Success] All bookings exported to 'gasgo_bookings.csv'.")

def view_consumers():
    print("\n--- Registered Consumers ---")
    print(f"{'ID':<6} {'Name':<18} {'Area':<14} {'Type':<10} {'Subsidy':<10} {'Last_Delivery':<12}")
    print("-" * 74)
    for c in consumers:
        c_type = "Single" if c["type"] == 1 else "Double"
        sub = "Yes" if c["subsidy"] else "No"
